"""Generate src/core/raster_lut.c: 0..255 coverage -> wire-order RGB565 grey.

The panel is driven in RGB565, so a grey has 32 usable levels (5-bit red/blue;
green's 6th bit is derived so the tint stays neutral). Coverage is converted
with a 2.2 gamma: an LCD's luminance is not linear in the code value, and
without it anti-aliased rims look thinner and more jagged than they are.
"""
import sys

GAMMA = 2.2
out = []
for c in range(256):
    v = (c / 255.0) ** (1.0 / GAMMA)
    r5 = int(round(v * 31))
    g6 = (r5 << 1) | (r5 >> 4)
    rgb = (r5 << 11) | (g6 << 5) | r5
    wire = ((rgb & 0xFF) << 8) | (rgb >> 8)  # high byte first on the bus
    out.append(wire)

with open(sys.argv[1], "w", newline="\n") as f:
    f.write("/* Generated by tools/gen_lut.py. Do not edit. */\n")
    f.write('#include "raster.h"\n\n')
    f.write("const uint16_t RASTER_LUT[256] = {\n")
    for i in range(0, 256, 8):
        f.write("    " + ", ".join("0x%04X" % v for v in out[i:i + 8]) + ",\n")
    f.write("};\n")
